import { readFile, writeFile } from "node:fs/promises";

const DEGREES = 2;
const TOP_LATITUDE = 84;
const BOTTOM_LATITUDE = -58;
const COLUMNS = 360 / DEGREES;
const ROWS = (TOP_LATITUDE - BOTTOM_LATITUDE) / DEGREES;
const SEA = " ";
const NO_COUNTRY = "~";
const FIRST_COUNTRY_CODE = 0x30;
const OUT_FILE = "ip-lookup/world.ts";

type Ring = [number, number][];
type Feature = {
  properties: { ISO_A2_EH: string; LABEL_X: number; LABEL_Y: number };
  geometry:
    | { type: "Polygon"; coordinates: Ring[] }
    | { type: "MultiPolygon"; coordinates: Ring[][] };
};

const source = process.argv[2];
if (!source) {
  throw new Error(
    "Pass the path of ne_110m_admin_0_countries.geojson from Natural Earth",
  );
}
const { features }: { features: Feature[] } = JSON.parse(
  await readFile(source, "utf8"),
);

const countries = features
  .filter((feature) => /^[A-Z]{2}$/.test(feature.properties.ISO_A2_EH))
  .sort((a, b) => a.properties.ISO_A2_EH.localeCompare(b.properties.ISO_A2_EH));

function rings(feature: Feature): Ring[] {
  return feature.geometry.type === "Polygon"
    ? feature.geometry.coordinates
    : feature.geometry.coordinates.flat();
}

function contains(polygon: Ring[], x: number, y: number) {
  let inside = false;
  for (const ring of polygon) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
        inside = !inside;
      }
    }
  }
  return inside;
}

let land = "";
for (let row = 0; row < ROWS; row++) {
  for (let column = 0; column < COLUMNS; column++) {
    const longitude = -180 + (column + 0.5) * DEGREES;
    const latitude = TOP_LATITUDE - (row + 0.5) * DEGREES;
    const feature = features.find((candidate) =>
      contains(rings(candidate), longitude, latitude),
    );
    const index = feature ? countries.indexOf(feature) : -1;
    land += !feature
      ? SEA
      : index === -1
        ? NO_COUNTRY
        : String.fromCharCode(FIRST_COUNTRY_CODE + index);
  }
}

await writeFile(
  OUT_FILE,
  `// Generated by scripts/world-map.ts from Natural Earth (public domain)

export const DEGREES = ${DEGREES};
export const TOP_LATITUDE = ${TOP_LATITUDE};
export const COLUMNS = ${COLUMNS};
export const ROWS = ${ROWS};
export const FIRST_COUNTRY_CODE = ${FIRST_COUNTRY_CODE};

export const COUNTRIES: [string, number, number][] = ${JSON.stringify(
    countries.map((feature) => [
      feature.properties.ISO_A2_EH,
      Number(feature.properties.LABEL_X.toFixed(2)),
      Number(feature.properties.LABEL_Y.toFixed(2)),
    ]),
  )};

export const LAND = ${JSON.stringify(land)};
`,
);
console.log(
  `Wrote ${countries.length} countries and ${land.replaceAll(SEA, "").length} land dots to ${OUT_FILE}`,
);
